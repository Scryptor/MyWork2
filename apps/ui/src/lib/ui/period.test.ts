import { describe, expect, it } from 'vitest';
import { periodRange } from './period.js';

describe('periodRange', () => {
	it.each([
		['week', '2026-11-25', ['2026-11-23', '2026-11-25']],
		['week', '2026-11-23', ['2026-11-23', '2026-11-23']],
		['week', '2026-11-29', ['2026-11-23', '2026-11-29']],
		['week', '2026-03-01', ['2026-02-23', '2026-03-01']],
		['month', '2026-11-25', ['2026-11-01', '2026-11-25']],
		['last_month', '2026-03-15', ['2026-02-01', '2026-02-28']],
		['last_month', '2028-03-10', ['2028-02-01', '2028-02-29']],
		['last_month', '2026-01-05', ['2025-12-01', '2025-12-31']],
		['year', '2026-11-25', ['2026-01-01', '2026-11-25']],
		['today', '2026-11-25', ['2026-11-25', '2026-11-25']],
		['all', '2026-11-25', [null, null]]
	] as const)('%s on %s', (kind, today, expected) => {
		expect(periodRange(kind, today)).toEqual(expected);
	});
});
