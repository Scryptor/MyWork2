//! Сборка маршрутов укладывается в небольшой стек.
//!
//! У главного потока на Windows всего 1 МБ стека, а отладочная сборка не делит слоты стека между
//! временными значениями: функция, где все `routes!(…)` шли одной цепочкой, росла с каждым
//! маршрутом и в плане 8.1 переполнила стек `mw-server` на Windows ещё до того, как он начал слушать
//! порт. Тест идёт отдельным файлом: переполнение стека обрывает весь процесс тестов.

#![allow(clippy::unwrap_used, clippy::expect_used)]

/// Запас стека для сборки маршрутов и документа OpenAPI. Разделы собираются по очереди, поэтому
/// пик — самый большой раздел, а не сумма. В отладочной сборке на macOS сборка требует около
/// 350 КБ (до разделения — больше 700 КБ); запас оставлен на более крупные кадры Windows.
const ROUTES_STACK: usize = 512 * 1024;

#[test]
fn building_the_routes_fits_a_small_stack() {
    let paths = std::thread::Builder::new()
        .stack_size(ROUTES_STACK)
        .spawn(|| mw_api::openapi().paths.paths.len())
        .unwrap()
        .join()
        .unwrap();
    assert!(paths > 0);
}
